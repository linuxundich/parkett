#!/usr/bin/env python3
"""Generates the Parkett app icon (parkett.svg).

Herringbone parquet floor in a rounded square, with a terminal pane set into
the top-left corner. GNOME HIG: 128 px canvas, body 104 x 100 at (12, 12),
4 px front edge, GNOME palette browns.
"""
import math, sys

WOOD = ['#dcbf9c', '#c49a6c', '#b5835a']   # light, mid, dark plank
GRAIN = '#000000'                          # grain lines, low opacity
GROUT = '#865e3c'
EDGE = '#63452c'
TERM, TERM_EDGE = '#241f31', '#0f0d15'
WHITE, GREEN = '#ffffff', '#2ec27e'

X0, Y0, IW, IH = 18, 18, 92, 88       # floor area inside the frame
PW, PL = 12, 36                       # plank width and length (unrotated)
CX, CY = 64, 62                       # pattern origin
grain = '--no-grain' not in sys.argv


def f(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def rot(x, y):
    a = math.radians(45)
    return (CX + x * math.cos(a) - y * math.sin(a),
            CY + x * math.sin(a) + y * math.cos(a))


def visible(x, y, w, h):
    pts = [rot(x, y), rot(x + w, y), rot(x, y + h), rot(x + w, y + h)]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return max(xs) > X0 and min(xs) < X0 + IW and max(ys) > Y0 and min(ys) < Y0 + IH


def plank(x, y, w, h, fill):
    s = f'      <rect x="{f(x)}" y="{f(y)}" width="{f(w)}" height="{f(h)}" rx="1.5" fill="{fill}"/>\n'
    if grain:  # one thin grain line along the plank
        if w > h:
            s += f'      <path d="M{f(x + 5)} {f(y + h * 0.55)} H{f(x + w - 9)}" stroke="{GRAIN}" stroke-opacity=".08" stroke-width="1.2" stroke-linecap="round"/>\n'
        else:
            s += f'      <path d="M{f(x + w * 0.55)} {f(y + 9)} V{f(y + h - 5)}" stroke="{GRAIN}" stroke-opacity=".08" stroke-width="1.2" stroke-linecap="round"/>\n'
    return s


floor = ''
for j in range(-4, 5):
    for i in range(-8, 9):
        ox, oy = i * PW - j * PL, i * PW + j * PL
        for (x, y, w, h, k) in ((ox + 1, oy + 1, PL - 2, PW - 2, (2 * i + 5 * j) % 3),
                                (ox + PL + 1, oy + PW - PL + 1, PW - 2, PL - 2, (2 * i + 5 * j + 2) % 3)):
            if visible(x, y, w, h):
                floor += plank(x, y, w, h, WOOD[k])

# terminal pane, top-left, with a grout border around it
tx, ty, tw, th = X0, Y0, 48, 44
px, py = tx + 11, ty + th / 2 - 1

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">
  <!-- Parkett: herringbone parquet floor with a terminal pane set into it.
       Generated by gen_icon.py; edit there, not here. -->
  <defs>
    <clipPath id="floor"><rect x="{X0}" y="{Y0}" width="{IW}" height="{IH}" rx="9"/></clipPath>
  </defs>
  <rect x="12" y="16" width="104" height="100" rx="14" fill="{EDGE}"/>
  <rect x="12" y="12" width="104" height="100" rx="14" fill="{GROUT}"/>
  <g clip-path="url(#floor)">
    <g transform="translate({CX} {CY}) rotate(45)">
{floor}    </g>
  </g>
  <rect x="{tx - 3}" y="{ty - 3}" width="{tw + 6}" height="{th + 8}" rx="9" fill="{GROUT}"/>
  <rect x="{tx}" y="{ty + 2}" width="{tw}" height="{th}" rx="6" fill="{TERM_EDGE}"/>
  <rect x="{tx}" y="{ty}" width="{tw}" height="{th}" rx="6" fill="{TERM}"/>
  <path d="M{px} {f(py - 8)} L{px + 9} {f(py)} L{px} {f(py + 8)}" fill="none" stroke="{WHITE}" stroke-width="4.5" stroke-linecap="round" stroke-linejoin="round"/>
  <rect x="{px + 14}" y="{f(py + 4)}" width="14" height="4.5" rx="1.5" fill="{GREEN}"/>
</svg>
'''
out = sys.argv[-1] if sys.argv[-1].endswith('.svg') else 'parkett.svg'
open(out, 'w').write(svg)
